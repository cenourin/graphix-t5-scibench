"""A4 (PORTABILIDADE.md §6.1): build graphix_modern/modeling_t5.py by applying the Graphix
changes, and only those, to transformers 4.57.6's models/t5/modeling_t5.py.

Run in the graphix-modern image, which has exactly that transformers:
  python scripts/port_build_modeling_t5.py
Every edit is anchored on a snippet that must occur the stated number of times, so a
different transformers version fails loudly instead of producing a subtly different model.
Also writes docs/port/modeling_t5_graphix.diff (upstream -> ported) for review.
"""
import difflib
import re
import sys
from pathlib import Path

import transformers
import transformers.models.t5.modeling_t5 as upstream

assert transformers.__version__ == "4.57.6", transformers.__version__
SRC = Path(upstream.__file__)
OUT = Path("graphix_modern/modeling_t5.py")
DIFF = Path("docs/port/modeling_t5_graphix.diff")

HEADER = '''# Graphix-T5 on transformers 4.57.6 (MODERN_A). GENERATED by
# scripts/port_build_modeling_t5.py from transformers/models/t5/modeling_t5.py 4.57.6;
# do not edit by hand, change the builder. Diff vs upstream: docs/port/modeling_t5_graphix.diff.
#
# Graphix changes, the same as the legacy fork (seq2seq/models/modeling_t5.py) made to
# transformers 4.17 (PORTABILIDADE.md §6.1):
#   - T5LayerRGAT: pre-norm, per-example graph caption through RGAT_Layer, ELU, dropout,
#     residual; with the legacy fork's unused `filter` Linear kept for checkpoint parity;
#   - one T5LayerRGAT per encoder block (T5Block.rgat_layer), run after the feed-forward
#     layer and before the fp16 clamp, as in the legacy fork;
#   - T5Stack.relation_emb = nn.Embedding(25, d_model) in encoder and decoder (the decoder's
#     is unused, kept for checkpoint parity);
#   - graph_batch threaded T5ForConditionalGeneration -> encoder T5Stack -> T5Block,
#     including under gradient checkpointing (GradientCheckpointingLayer binds kwargs);
#   - the Graphix-added modules get torch's default initialization, which is what they got
#     in the legacy fork: 4.57's from_pretrained initializes missing weights only through
#     _init_weights, which does not know plain nn.Linear/nn.Embedding/nn.LayerNorm.
# Not ported: the legacy fork's fp16/bf16 upcasts (PORTABILIDADE.md §6.2), which are no-ops
# in fp32, and nothing else is changed.
'''

T5_LAYER_RGAT = '''class T5LayerRGAT(nn.Module):
    """Graphix: relational graph attention over the question/schema graph (legacy fork,
    unchanged except number_of_nodes() -> num_nodes())."""

    def __init__(self, config):
        super().__init__()
        self.rgat = RGAT_Layer(config.d_model, config.d_model, num_heads=1, feat_drop=0.2)
        self.filter = nn.Linear(config.d_ff, config.d_model, bias=False)  # unused, as in the legacy fork
        self.layer_norm = T5LayerNorm(config.d_model, eps=config.layer_norm_epsilon)
        self.dropout = nn.Dropout(config.dropout_rate)
        self.dropout_gnn = nn.Dropout(config.dropout_rate)
        for module in self.modules():
            if not isinstance(module, T5LayerNorm):
                module._graphix_default_init = True

    def forward(self, hidden_states, graph_batch, relation_emb):
        hs_norm = self.layer_norm(hidden_states)
        graph_rep = self.graph_caption(hs_norm, graph_batch, relation_emb)

        output = F.elu(graph_rep)
        output = self.dropout_gnn(output)

        layer_output = hidden_states + self.dropout(output)
        return layer_output

    def graph_caption(self, hidden_states, graph_batch, relation_emb):
        """
        :param hidden_states: [bsz x input_max_length x d_model]
        :return: hidden states with graph caption, while keeping the other reps
        """
        for i, graph in enumerate(graph_batch):
            hidden_states[i] = self.graph_caption_one(hidden_states[i], graph['graph'],
                                                      graph['edges'], relation_emb)

        return hidden_states

    def graph_caption_one(self, hidden_state, graph, edges, relation_emb):
        num_nodes = graph.num_nodes()
        node_feats = hidden_state[:num_nodes]
        edge_feats = relation_emb(edges)

        struct_rep, edge_feats = self.rgat(node_feats, edge_feats, graph)
        hidden_state[:num_nodes] = struct_rep

        return hidden_state


'''

GRAPHIX_INIT = '''        if getattr(module, "_graphix_default_init", False):
            # Graphix-added module: torch's default initialization, as in the legacy fork.
            if isinstance(module, nn.Linear):
                bound = 1.0 / math.sqrt(module.in_features)  # kaiming_uniform_(a=sqrt(5))
                module.weight.data.uniform_(-bound, bound)
                if module.bias is not None:
                    module.bias.data.uniform_(-bound, bound)
            elif isinstance(module, nn.Embedding):
                module.weight.data.normal_(mean=0.0, std=1.0)
            elif isinstance(module, nn.LayerNorm):
                module.weight.data.fill_(1.0)
                module.bias.data.zero_()
            return
'''


def sub(text, old, new, count=1, nth=None):
    found = text.count(old)
    if found != count:
        sys.exit("anchor found %d times, expected %d:\n%s" % (found, count, old))
    if nth is None:
        return text.replace(old, new)
    parts = text.split(old)
    return old.join(parts[:nth]) + new + old.join(parts[nth:])


def main():
    src = SRC.read_text()
    t = src
    # 1. relative imports -> absolute (the file now lives outside the transformers package)
    t = re.sub(r"^(\s*)from \.\.\.", r"\1from transformers.", t, flags=re.M)
    t = sub(t, "from .configuration_t5 import T5Config", "from transformers.models.t5.configuration_t5 import T5Config")
    # 2. Graphix imports
    t = sub(t, "from transformers.models.t5.configuration_t5 import T5Config\n",
            "from transformers.models.t5.configuration_t5 import T5Config\n\n"
            "import torch.nn.functional as F\n"
            "from .rgat_tuning import RGAT_Layer\n")
    # 3. T5LayerRGAT
    t = sub(t, "class T5Attention(nn.Module):", T5_LAYER_RGAT + "class T5Attention(nn.Module):")
    # 4. one RGAT layer per encoder block
    t = sub(t, "        self.layer.append(T5LayerFF(config))\n",
            "        self.layer.append(T5LayerFF(config))\n\n"
            "        # Graphix: one RGAT layer per encoder block\n"
            "        if not self.is_decoder:\n"
            "            self.rgat_layer = T5LayerRGAT(config)\n")
    # 5. T5Block.forward accepts the graph
    t = sub(t, "        cache_position=None,\n    ):\n        self_attention_outputs = self.layer[0](",
            "        cache_position=None,\n        graph_batch=None,\n        relation_emb=None,\n    ):\n"
            "        self_attention_outputs = self.layer[0](")
    # 6. RGAT after the feed-forward layer, before the fp16 clamp (legacy order)
    t = sub(t, "        # Apply Feed Forward layer\n        hidden_states = self.layer[-1](hidden_states)\n",
            "        # Apply Feed Forward layer\n        hidden_states = self.layer[-1](hidden_states)\n\n"
            "        # Graphix: replace the token representations with their RGAT-ed ones\n"
            "        if not self.is_decoder:\n"
            "            hidden_states = self.rgat_layer(hidden_states, graph_batch, relation_emb)\n")
    # 7. relation embeddings (encoder and decoder stacks, as in the legacy fork)
    t = sub(t, "        self.dropout = nn.Dropout(config.dropout_rate)\n\n"
               "        # Initialize weights and apply final processing\n        self.post_init()\n"
               "        # Model parallel\n",
            "        self.dropout = nn.Dropout(config.dropout_rate)\n\n"
            "        # Graphix: relation embeddings of the 25 GRAPHIX_RELATIONS\n"
            "        self.relation_emb = nn.Embedding(25, config.d_model)\n"
            "        self.relation_emb._graphix_default_init = True\n\n"
            "        # Initialize weights and apply final processing\n        self.post_init()\n"
            "        # Model parallel\n")
    # 8. T5Stack.forward accepts the graph (relation_emb kept in the signature, as in the fork)
    t = sub(t, "        return_dict=None,\n        cache_position=None,\n    ):\n        # Model parallel\n"
               "        if self.model_parallel:\n            torch.cuda.set_device(self.first_device)",
            "        return_dict=None,\n        cache_position=None,\n        graph_batch=None,\n"
            "        relation_emb=None,\n    ):\n        # Model parallel\n"
            "        if self.model_parallel:\n            torch.cuda.set_device(self.first_device)")
    # 9. ... and hands it to every block, with the stack's own relation embeddings
    t = sub(t, "                return_dict=return_dict,\n                cache_position=cache_position,\n"
               "            )\n\n            hidden_states = layer_outputs[0]",
            "                return_dict=return_dict,\n                cache_position=cache_position,\n"
            "                graph_batch=graph_batch,\n                relation_emb=self.relation_emb,\n"
            "            )\n\n            hidden_states = layer_outputs[0]")
    # 10. T5ForConditionalGeneration.forward accepts the graph
    t = sub(t, "        cache_position: Optional[torch.LongTensor] = None,\n"
               "    ) -> Union[tuple[torch.FloatTensor], Seq2SeqLMOutput]:",
            "        cache_position: Optional[torch.LongTensor] = None,\n        graph_batch=None,\n"
            "    ) -> Union[tuple[torch.FloatTensor], Seq2SeqLMOutput]:")
    # 11. ... and passes it to the encoder: the 2nd of three identical encoder calls is
    #     T5ForConditionalGeneration's (1st T5Model, 3rd T5ForQuestionAnswering, both left
    #     untouched as in the fork)
    enc = ("            encoder_outputs = self.encoder(\n                input_ids=input_ids,\n"
           "                attention_mask=attention_mask,\n                inputs_embeds=inputs_embeds,\n"
           "                head_mask=head_mask,\n                output_attentions=output_attentions,\n"
           "                output_hidden_states=output_hidden_states,\n                return_dict=return_dict,\n"
           "            )\n")
    t = sub(t, enc, enc.replace("                return_dict=return_dict,\n",
                                "                return_dict=return_dict,\n                graph_batch=graph_batch,\n"),
            count=3, nth=2)
    at = t.index("graph_batch=graph_batch,\n            )\n")
    assert t.index("class T5ForConditionalGeneration") < at < t.index("class T5EncoderModel"), "encoder call patched outside T5ForConditionalGeneration"
    # 12. torch default init for the Graphix-added modules
    t = sub(t, '        factor = self.config.initializer_factor  # Used for testing weights initialization\n',
            GRAPHIX_INIT + '        factor = self.config.initializer_factor  # Used for testing weights initialization\n')

    t = HEADER + t
    OUT.write_text(t)
    DIFF.parent.mkdir(parents=True, exist_ok=True)
    DIFF.write_text("".join(difflib.unified_diff(
        src.splitlines(True), t.splitlines(True),
        "transformers-4.57.6/models/t5/modeling_t5.py", "graphix_modern/modeling_t5.py")))
    print("wrote", OUT, "and", DIFF)


if __name__ == "__main__":
    main()
